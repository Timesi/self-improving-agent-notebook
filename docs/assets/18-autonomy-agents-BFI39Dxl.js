    "\\n",
    "class NoisyBrain:\\n",
    "    '''一个单步正确率有限的求解器：先调 LLM，再按错误率把结果改错。\\n",
    "\\n",
    "    真实模式中模型本身就可能出错；这里用可调错误率做受控实验，\\n",
    "    便于单独观察自检与重试机制的作用。错误是瞬时的，重试可以撞对。\\n",
    "    '''\\n",
    "\\n",
    "    def __init__(self, client, err_prob=0.35, seed=0):\\n",
    "        self.client = client\\n",
    "        self.err_prob = err_prob\\n",
    "        self.rng = np.random.RandomState(seed)\\n",
    "\\n",
    "    def solve(self, expr):\\n",
    "        '''求解表达式：以 err_prob 概率返回一个错误值，否则返回 LLM 结果。'''\\n",
    "        value = llm_solve(self.client, expr)\\n",
    "        if self.rng.rand() < self.err_prob:\\n",
    "            return value + self.rng.randint(1, 5)\\n",
    "        return value\\n",
    "\\n",
    "\\n",
    "def exact_check(expr, answer):\\n",
    "    '''硬验证：重算真值并精确比较，任何偏差都判定为错。'''\\n",
    "    a, b = (int(x) for x in expr.split('加'))\\n",
    "    return answer == a + b\\n",
    "\\n",
    "\\n",
    "def llm_check(client, expr, answer, rng):\\n",
    "    '''弱自检：把答案交给 LLM 复核，复核几乎总是说“看起来对”。\\n",
    "\\n",
    "    mock 模式下复核没有独立判定能力，按 94% 概率放行，\\n",
    "    对应 Self-Refine 论文里“模型对 94% 的错误样本都说看起来对”的负结果。\\n",
