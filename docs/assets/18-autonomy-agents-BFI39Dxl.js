    "class AgentLoop:\\n",
    "    '''带自检与重试上限的 agent 循环。\\n",
    "\\n",
    "    流程：求解 -> 自检。checker 为 None 时不验证，直接接受结果；\\n",
    "    验证失败则在剩余尝试次数内重试，次数用尽仍未通过则放弃本步。\\n",
